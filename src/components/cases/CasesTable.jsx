/** Cases table */
import { Eye } from 'lucide-react'
import { Link } from 'react-router-dom'
import StatusBadge from '../ui/StatusBadge'
import Table from '../ui/Table'
import { formatIndianCurrency } from '../../utils/helpers'

const columns = [
  {
    key: 'index',
    label: '#',
    width: '5%',
    render: (_row, idx) => (
      <span className="font-semibold text-[#1a2b3c]">{idx + 1}</span>
    ),
  },
  {
    key: 'caseName',
    label: 'Case Name',
    width: '17%',
    render: (row) => (
      <Link
        to={`/cases/${row.id}`}
        className="font-medium text-[#2b7de9] hover:underline"
      >
        {row.caseName}
      </Link>
    ),
  },
  {
    key: 'caseCreatedBy',
    label: 'Case Created by',
    width: '15%',
    render: (row) => row.caseCreatedBy || 'N/A',
  },
  {
    key: 'quoteGeneratedBy',
    label: 'Quote Generated by',
    width: '15%',
    render: (row) => row.quoteGeneratedBy || 'N/A',
  },
  {
    key: 'loanAmount',
    label: 'Loan Amount',
    width: '13%',
    render: (row) => formatIndianCurrency(row.loanAmount),
  },
  {
    key: 'status',
    label: 'Status',
    width: '22%',
    render: (row) => <StatusBadge status={row.status} />,
  },
  {
    key: 'action',
    label: 'Action',
    width: '13%',
    render: (row) => (
      <Link
        to={`/cases/${row.id}`}
        className="inline-flex items-center gap-1.5 whitespace-nowrap text-sm font-medium text-[#2b7de9] hover:underline"
      >
        <Eye className="h-4 w-4 shrink-0" strokeWidth={1.75} />
        View Case
      </Link>
    ),
  },
]

export default function CasesTable({ cases, className, startIndex = 0 }) {
  const cols = columns.map((col) =>
    col.key === 'index'
      ? {
          ...col,
          render: (_row, idx) => (
            <span className="font-semibold text-[#1a2b3c]">
              {startIndex + idx + 1}
            </span>
          ),
        }
      : col,
  )

  return <Table columns={cols} rows={cases} className={className} />
}
